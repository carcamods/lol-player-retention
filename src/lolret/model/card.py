"""Render `model_card.md` from the metrics `lolret train` writes."""

from typing import Any

from lolret.model.data import FEATURES

LABELS = {
    "majority": "Majority class",
    "recency": "Recency rule",
    "logreg": "Logistic regression",
    "lightgbm": "LightGBM",
    "mlp": "MLP",
    "gru": "GRU",
    "lightgbm_gru": "LightGBM + GRU average",
}
PRELIMINARY_BELOW = 200  # test churners; fewer means a partial dataset and wide intervals
TOP_FEATURES = 10


def _num(value: float | None, digits: int = 3) -> str:
    return "n/a" if value is None else f"{value:.{digits}f}"


def with_ci(value: float | None, ci: list[float] | None) -> str:
    if value is None:
        return "n/a"
    return _num(value) if ci is None else f"{_num(value)} ({_num(ci[0])}, {_num(ci[1])})"


def _signed(value: float) -> str:
    return f"{value:+.3f}"


def verdict(name: str, comparison: dict[str, Any], baseline: str) -> str:
    diff, ci = comparison["pr_auc_diff"], comparison["pr_auc_diff_ci"]
    model, base = LABELS.get(name, name), LABELS[baseline].lower()
    if ci is None:
        return f"- {model}: PR-AUC difference {_signed(diff)} (no interval)."
    span = f"{_signed(ci[0])} to {_signed(ci[1])}"
    if ci[0] > 0:
        return f"- {model} **beats** the {base} by {_signed(diff)} PR-AUC (95% CI {span})."
    if ci[1] < 0:
        return f"- {model} is **worse** than the {base} by {-diff:.3f} PR-AUC (95% CI {span})."
    return (
        f"- {model} does **not clearly beat** the {base}: difference {_signed(diff)} PR-AUC "
        f"(95% CI {span})."
    )


def _against_lightgbm(name: str, comparison: dict[str, Any]) -> str:
    diff, ci = comparison["pr_auc_diff"], comparison["pr_auc_diff_ci"]
    model = LABELS.get(name, name)
    if ci is None:
        return f"- {model}: PR-AUC difference {_signed(diff)} (no interval)."
    span = f"95% CI {_signed(ci[0])} to {_signed(ci[1])}"
    if ci[0] > 0:
        return f"- {model} **beats** LightGBM by {_signed(diff)} PR-AUC ({span})."
    if ci[1] < 0:
        return f"- {model} is **worse** than LightGBM by {-diff:.3f} PR-AUC ({span})."
    return f"- {model} is **level** with LightGBM: difference {_signed(diff)} PR-AUC ({span})."


def _neural_nets(m: dict[str, Any]) -> list[str]:
    """The section `lolret train-nn` adds; empty before it has run."""
    if "nn" not in m:
        return []
    nn, sel = m["nn"], m["nn"]["selection"]
    cfg = nn["config"]
    hidden = ", ".join(str(h) for h in cfg["mlp_hidden"])
    return [
        "## Neural nets",
        "",
        f"- **MLP:** hidden layers of {hidden} units on the same {len(FEATURES)} features, "
        f"prepared like the logistic regression's; {sel['mlp']['epochs']} epochs.",
        f"- **GRU:** reads the last 20 matches that finished before the cutoff, oldest first "
        "(result, kills, deaths, assists, duration, queue, role, time to the cutoff, gap since "
        f"the previous game). Its last state ({cfg['gru_hidden']} units) joins a layer over the "
        f"{len(FEATURES)} features; {sel['gru']['epochs']} epochs.",
        f"- **Both:** {cfg['seeds']} nets averaged, each early-stopped on the same "
        "player-grouped folds as the classical models, whose out-of-fold predictions also fit "
        "the Platt scaling. The test set chooses nothing.",
        "- **LightGBM + GRU average:** the mean of the two calibrated probabilities.",
        "",
        "**Against LightGBM**, paired on the same resamples:",
        "",
        *(_against_lightgbm(name, c) for name, c in nn["vs_lightgbm"].items()),
        "",
    ]


def render_model_card(m: dict[str, Any]) -> str:
    train, test = m["data"]["train"], m["data"]["test"]
    baseline = m["baseline"]
    lines = ["# Model card: will a ranked player stop playing in the next 28 days?", ""]
    if test["churned"] < PRELIMINARY_BELOW:
        lines += [
            f"> **Preliminary.** The test set has only {test['churned']} churned players, so "
            "the intervals are wide and the numbers will move as the dataset grows.",
            "",
        ]
    lines += [
        f"Generated by `lolret train` (lolret {m['lolret_version']}) on {m['created'][:10]} "
        f"from dataset `{m['dataset']}`.",
        "",
        "## Task",
        "",
        "For a ranked League of Legends player who played in the 28 days before a cutoff date T, "
        "predict whether they will play no game at all, in any queue, in the 28 days after T. "
        "Features use only data from before T (ADR 0003, ADR 0006).",
        "",
        "## Data",
        "",
        "| | Train | Test |",
        "|---|---|---|",
        f"| Cutoffs | {', '.join(train['cutoffs'])} | {', '.join(test['cutoffs'])} |",
        f"| Players | {train['players']:,} | {test['players']:,} |",
        f"| Examples | {train['examples']:,} | {test['examples']:,} |",
        f"| Churn rate | {train['churn_rate']:.1%} | {test['churn_rate']:.1%} |",
        "",
        "Test players are held out completely: none of their examples are used in training, and "
        "the test cutoff comes after every training label is known (ADR 0008).",
        "",
        "## Results on the test set",
        "",
        "95% bootstrap intervals in parentheses.",
        "",
        "| Model | PR-AUC | ROC-AUC | Brier |",
        "|---|---|---|---|",
    ]
    for name, r in m["test"].items():
        lines.append(
            f"| {LABELS[name]} | {with_ci(r['pr_auc'], r['pr_auc_ci'])} | "
            f"{with_ci(r['roc_auc'], r['roc_auc_ci'])} | {with_ci(r['brier'], r['brier_ci'])} |"
        )
    lines += [
        "",
        f"A random ranking scores a PR-AUC equal to the churn rate ({test['churn_rate']:.3f}). "
        "Lower Brier is better.",
        "",
        f"**Against the {LABELS[baseline].lower()}** (days since the last game), "
        "paired on the same resamples:",
        "",
        *(verdict(name, c, baseline) for name, c in m["vs_baseline"].items() if name != "majority"),
        "",
        "## Calibration (LightGBM)",
        "",
        "Test examples in equal-count bins by predicted probability.",
        "",
        "| Predicted | Observed | Examples |",
        "|---|---|---|",
        *(
            f"| {b['predicted']:.3f} | {b['observed']:.3f} | {b['n']} |"
            for b in m["reliability"]["lightgbm"]
        ),
        "",
        "## What drives the LightGBM predictions",
        "",
        "Mean absolute SHAP value (log-odds) on the test set, top features.",
        "",
        "| Feature | Mean \\|SHAP\\| |",
        "|---|---|",
        *(
            f"| `{feature}` | {value:.3f} |"
            for feature, value in list(m["importance"]["lightgbm_mean_abs_shap"].items())[
                :TOP_FEATURES
            ]
        ),
        "",
        "Definitions: docs/features.md.",
        "",
        "## Models",
        "",
        "- **Majority class:** predicts the training churn rate for everyone.",
        "- **Recency rule:** ranks players by days since their last game; a one-feature "
        "logistic fit on log(1 + days) turns that into a probability.",
        f"- **Logistic regression:** L2, C = {m['selection']['logreg_c']} chosen by "
        "player-grouped cross-validation; signed log(1 + |x|) inputs, median imputation with "
        "missing-value indicators, standardised.",
        f"- **LightGBM:** {m['selection']['lightgbm_rounds']} rounds (mean early-stopping point "
        "across the cross-validation folds); missing values handled natively.",
        "- **Calibration:** both are Platt-scaled on their out-of-fold predictions from the same "
        "player-grouped folds.",
        f"- **Inputs:** {len(FEATURES)} point-in-time features. Never ladder wins, losses, LP or "
        "flags, which are measured after T.",
        "",
        *_neural_nets(m),
        "## Limitations",
        "",
        "- Players are sampled from the current ladder, which under-represents players who quit "
        "before the current split.",
        "- NA1, EUW1 and KR only, Iron to Diamond, and three cutoffs from one season.",
        "- Churn means no game for 28 days. Some churned players come back later.",
        "- Tier and division are measured at collection time, so they are not features.",
        "",
    ]
    return "\n".join(lines)
